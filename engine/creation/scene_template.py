# ──── Scaffolding Function ───────────────────────────────────────────────


def _hex_to_rgb(hex_color: str) -> str:
    """Convert hex color to space-separated RGB string.

    Args:
        hex_color: CSS hex color (e.g. ``"#06b6d4"``).

    Returns:
        Space-separated RGB string (e.g. ``"6 182 212"``).
    """
    hex_color = hex_color.lstrip("#")
    if len(hex_color) == 3:
        hex_color = "".join(c * 2 for c in hex_color)
    try:
        r, g, b = int(hex_color[0:2], 16), int(hex_color[2:4], 16), int(hex_color[4:6], 16)
        return f"{r} {g} {b}"
    except (ValueError, IndexError):
        return "6 182 212"


def _hex_to_rgb_csv(hex_color: str) -> str:
    """Convert hex color to comma-separated RGB for CSS rgba().

    Args:
        hex_color: CSS hex color (e.g. ``"#06b6d4"``).

    Returns:
        Comma-separated RGB string (e.g. ``"6, 182, 212"``).
    """
    return _hex_to_rgb(hex_color).replace(" ", ", ")


def create_scene(
    name: str,
    display_name: Optional[str] = None,
    port: int = 5590,
    accent: str = "#00e5ff",
    description: str = "",
    template: str = "basic",
    generate_test: bool = True,
    auto_register: bool = True,
) -> Path:
    """Scaffold a new scene directory with production-quality boilerplate.

    Generates: ``{name}_scene.py``, ``{name}.html``, ``{name}.js``,
    ``{name}.css``, ``test_{name}.py``, and ``__init__.py``.  Optionally
    registers the scene in ``control_plane_registry.py`` and
    ``config/launcher.yaml``.

    Args:
        name: Machine name (snake_case, e.g. ``"my_scene"``).
        display_name: Human-readable name. Defaults to title-cased *name*.
        port: Default port assignment.
        accent: CSS accent colour hex.
        description: Short scene description.
        template: Template variant (currently only ``"basic"``).
        generate_test: If True, also create ``tests/test_{name}.py``.
        auto_register: If True, add scene to control_plane_registry and
                       launcher.yaml.

    Returns:
        Path to the created scene directory.

    Raises:
        FileExistsError: If the scene directory already exists.
    """
    scene_dir = SCENES_DIR / name
    if scene_dir.exists():
        raise FileExistsError(f"Scene directory already exists: {scene_dir}")

    display_name = display_name or name.replace("_", " ").title()
    class_name = "".join(w.capitalize() for w in name.split("_")) + "Scene"
    app_var = class_name.replace("Scene", "App")
    today = date.today().isoformat()
    accent_rgb = _hex_to_rgb(accent)
    accent_rgb_csv = _hex_to_rgb_csv(accent)

    header_line = "=" * (len(display_name) + len(" — CosySim Scene"))
    js_header_line = "=" * (len(name) + len(".js — ") + len(display_name) + len(" Scene Controller"))
    css_header_line = "=" * (len(name) + len(".css — ") + len(display_name) + len(" Scene Styles"))
    test_header_line = "=" * (len("Tests for ") + len(display_name) + len(" Scene"))

    ctx = {
        "name": name,
        "display_name": display_name,
        "class_name": class_name,
        "app_var": app_var,
        "port": port,
        "accent": accent,
        "accent_rgb": accent_rgb,
        "accent_rgb_csv": accent_rgb_csv,
        "description": description or f"{display_name} scene",
        "header_line": header_line,
        "js_header_line": js_header_line,
        "css_header_line": css_header_line,
        "test_header_line": test_header_line,
        "today": today,
    }

    # ── Create directory structure ────────────────────────────────────
    (scene_dir / "templates").mkdir(parents=True, exist_ok=True)
    (scene_dir / "static").mkdir(parents=True, exist_ok=True)

    # ── Write scene files ────────────────────────────────────────────
    (scene_dir / "__init__.py").write_text(
        f'"""CosySim scene: {display_name}."""\n', encoding="utf-8"
    )
    (scene_dir / f"{name}_scene.py").write_text(
        _SCENE_PY_TEMPLATE.format(**ctx), encoding="utf-8"
    )
    (scene_dir / "templates" / f"{name}.html").write_text(
        _HTML_TEMPLATE.format(**ctx), encoding="utf-8"
    )
    (scene_dir / "static" / f"{name}.js").write_text(
        _JS_TEMPLATE.format(**ctx), encoding="utf-8"
    )
    (scene_dir / "static" / f"{name}.css").write_text(
        _CSS_TEMPLATE.format(**ctx), encoding="utf-8"
    )

    # ── Write test file ──────────────────────────────────────────────
    if generate_test:
        test_dir = PROJECT_ROOT / "tests"
        test_file = test_dir / f"test_{name}.py"
        if not test_file.exists():
            test_file.write_text(_TEST_TEMPLATE.format(**ctx), encoding="utf-8")
            logger.info("Generated test file: %s", test_file)

    # ── Auto-register in control plane ───────────────────────────────
    if auto_register:
        _register_scene(name, display_name, class_name, port, accent)

    logger.info("Scaffolded scene '%s' at %s", name, scene_dir)
    return scene_dir


