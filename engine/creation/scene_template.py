# v1.52.0 [2026-03-22] — Register new scenes in control_plane_registry + launcher.yaml
# CONNECTS: control_plane_registry.py, config/launcher.yaml
# CALLED BY: create_scene() when auto_register=True


def _register_scene(
    name: str,
    display_name: str,
    class_name: str,
    port: int,
    accent: str,
) -> None:
    """Register a scene in control_plane_registry.py and launcher.yaml.

    Appends the scene to ``SCENE_DEFS`` in the registry module and adds
    an entry to ``config/launcher.yaml`` under ``scenes:``.

    Args:
        name: Scene machine name (snake_case).
        display_name: Scene display name.
        class_name: Scene class name (PascalCase + "Scene").
        port: Default port.
        accent: CSS accent colour hex.
    """
    # ── Register in control_plane_registry.py ────────────────────────
    registry_path = PROJECT_ROOT / "engine" / "control_plane_registry.py"
    if registry_path.exists():
        content = registry_path.read_text(encoding="utf-8")
        # Check if already registered
        if f'"{name}"' in content and "SCENE_DEFS" in content:
            logger.debug("Scene '%s' already in control_plane_registry", name)
        else:
            # Find the closing brace of SCENE_DEFS and insert before it
            cls_path = f"content.scenes.{name}.{name}_scene.{class_name}"
            entry = (
                f'    # v1.52.0 — Auto-registered by Creation Kit\n'
                f'    "{name}": {{\n'
                f'        "type": "flask",\n'
                f'        "cls": "{cls_path}",\n'
                f'        "label": "{display_name}",\n'
                f'        "auto_start": False,\n'
                f'        "pillar": "game",\n'
                f'    }},\n'
            )
            # Insert before the closing "}" of SCENE_DEFS
            # Find the pattern: last entry in SCENE_DEFS followed by "}"
            marker = "}\n\n# ──── Derived ID Tuples"
            if marker in content:
                content = content.replace(marker, entry + "}\n\n# ──── Derived ID Tuples")
                registry_path.write_text(content, encoding="utf-8")
                logger.info("Registered '%s' in control_plane_registry.py", name)
            else:
                logger.warning("Could not find SCENE_DEFS closing marker in control_plane_registry.py")

    # ── Register in launcher.yaml ────────────────────────────────────
    launcher_yaml = PROJECT_ROOT / "config" / "launcher.yaml"
    if launcher_yaml.exists():
        yaml_content = launcher_yaml.read_text(encoding="utf-8")
        if f"  {name}:" not in yaml_content:
            # Find the "scenes:" section and append
            scenes_entry = f"  {name}:\n    auto_start: false\n"
            if "scenes:" in yaml_content:
                # Insert after "scenes:" line
                yaml_content = yaml_content.replace(
                    "scenes:\n", f"scenes:\n{scenes_entry}", 1
                )
                launcher_yaml.write_text(yaml_content, encoding="utf-8")
                logger.info("Registered '%s' in launcher.yaml", name)
        else:
            logger.debug("Scene '%s' already in launcher.yaml", name)

    # ── Register port ────────────────────────────────────────────────
    port_registry = PROJECT_ROOT / "engine" / "port_registry.py"
    if port_registry.exists():
        port_content = port_registry.read_text(encoding="utf-8")
        if f'"{name}"' not in port_content:
            # Find _DEFAULT_PORTS dict and add entry
            marker = "}\n\n# Aliases"
            if "_DEFAULT_PORTS" in port_content and marker in port_content:
                port_entry = f'    "{name}": {port},\n'
                port_content = port_content.replace(marker, port_entry + marker)
                port_registry.write_text(port_content, encoding="utf-8")
                logger.info("Registered port %d for '%s' in port_registry.py", port, name)
